import fs from 'node:fs';
import {createHash} from 'node:crypto';
const manifest=JSON.parse(fs.readFileSync(process.argv[2]));
const read=file=>JSON.parse(fs.readFileSync(file));
const comparison=read(manifest.comparison),recalls=read(manifest.recalls);
const corpus=read(manifest.targetCorpus),legacy=read(manifest.legacyCorpus);
const baseline=comparison.results.find(r=>r.model===manifest.baselineModel);
const loss=(result,source)=>result.partitions.find(p=>p.sourceSha256===source)?.loss;
const baselineLoss=loss(baseline,legacy.sourceSha256);
const completed=read(manifest.longTraining);
if(completed.training.completedSteps!==1000000||completed.training.completedRounds!==10||completed.rounds.length!==10)throw Error('Ten requested rounds are incomplete');
const candidates=manifest.candidates.map(candidate=>{
 const source=fs.readFileSync(candidate.model),sha=createHash('sha256').update(source).digest('hex');
 const measured=comparison.results.find(r=>r.model===candidate.model);
 const recall=recalls.find(r=>r.modelSha256===sha&&r.checkpointStep===null);
 const trace=read(candidate.training);
 const targetLoss=loss(measured,corpus.sourceSha256),legacyLoss=loss(measured,legacy.sourceSha256);
 if(measured?.sha256!==sha||!Number.isFinite(targetLoss)||!Number.isFinite(legacyLoss))throw Error('Missing identical-corpus comparison: '+candidate.model);
 const eligible=recall?.exact===140&&recall.rows===140&&legacyLoss<=baselineLoss*1.02&&trace.training.completedSteps===10000;
 return {...candidate,targetLoss,legacyLoss,eligible,modelSha256:sha};
});
const selected=candidates.filter(c=>c.eligible).sort((a,b)=>a.targetLoss-b.targetLoss)[0];
if(!selected)throw Error('No candidate preserved facts and validation');
const initial=JSON.parse(fs.readFileSync(selected.initializerFile,'utf8').split('export const neuralModel=')[1].trim().replace(/;$/,''));
fs.copyFileSync(selected.model,'docs/neural-model.js');
fs.copyFileSync(selected.training,'training/transformer-training.json');
fs.copyFileSync(selected.reference,'training/transformer-reference.json');
const report={selected:selected.name,trainingCorpus:selected.corpus,initializerFile:selected.initializerFile,initializerCumulativeSteps:initial.training.cumulativeCheckpointSteps,modelSha256:selected.modelSha256,totalCompletedSteps:1000000+candidates.reduce((n,c)=>n+read(c.training).training.completedSteps,0),minimumUpdates:0,reason:'Every requested long-training round was completed. Selected the lowest loss on identical current grammar-validation rows among own candidates preserving all 140 sourced literal rows and legacy validation within 2%. External language holdout was not consulted.',comparison:manifest.comparison,literalRecall:manifest.recalls,longTraining:manifest.longTraining,candidates};
fs.writeFileSync('training/transformer-selection.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({selected:selected.name,loss:selected.targetLoss,legacyLoss:selected.legacyLoss,modelSha256:selected.modelSha256}));
