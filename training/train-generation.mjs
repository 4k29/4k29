import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {generationGrammar} from '../docs/generation-grammar.js';

// Deterministic CPU training: weighted 1–4-gram counts plus a pairwise
// logistic preference model. No profile values, evaluation questions or network.
export const featureNames=['styleMatch','brevityFit','detailFit','directness','fluency','naturalness','novelty'];
export function tokenize(template,language){
 const segmenter=new Intl.Segmenter(language,{granularity:'word'}),tokens=[];
 for(const piece of template.split(/(\{value\}|\{label\})/).filter(Boolean)){
  if(/^\{(?:value|label)\}$/.test(piece))tokens.push(piece);
  else tokens.push(...[...segmenter.segment(piece)].map(x=>x.segment));
 }
 return tokens;
}
const dot=(a,b)=>a.reduce((sum,x,i)=>sum+x*b[i],0);
const sigmoid=x=>x>=0?1/(1+Math.exp(-x)):Math.exp(x)/(1+Math.exp(x));
export function trainPreference(pairs,epochs=600){
 const weights=featureNames.map(()=>0),loss=()=>pairs.reduce((sum,p)=>sum+Math.log1p(Math.exp(-dot(weights,p.preferred.map((v,i)=>v-p.other[i])))),0)/pairs.length;
 const initialLoss=loss();
 for(let epoch=0;epoch<epochs;epoch++){
  const gradient=weights.map(w=>.006*w);
  for(const pair of pairs){const difference=pair.preferred.map((v,i)=>v-pair.other[i]),error=1-sigmoid(dot(weights,difference));for(let i=0;i<weights.length;i++)gradient[i]-=error*difference[i]/pairs.length;}
  for(let i=0;i<weights.length;i++)weights[i]-=.35*gradient[i];
 }
 return {weights:weights.map(x=>Number(x.toFixed(7))),initialLoss,finalLoss:loss(),epochs};
}
export function trainGeneration(rows=generationGrammar){
 const vocabulary=['<bos>','<eos>','<unk>'],ids=new Map(vocabulary.map((t,i)=>[t,i])),counts={},compiled=[],scopeNames=[],scopeIds=new Map();
 const tokenId=t=>{if(!ids.has(t)){ids.set(t,vocabulary.length);vocabulary.push(t);}return ids.get(t);};
 for(const row of rows){
  if((row.template.match(/\{value\}/g)||[]).length!==1||/\{(?!value|label)/.test(row.template))throw Error('Invalid fact slot: '+row.id);
  const tokens=tokenize(row.template,row.language).map(tokenId);
  const {template,weight,...metadata}=row;
  compiled.push({...metadata,tokens});
  // Factor relation and style to share evidence instead of duplicating every
  // relation/style combination. Numeric scope IDs keep the shipped model small.
  const scopes=[row.language+':'+row.kind+':*',row.language+':*:'+row.style].map(scope=>{if(!scopeIds.has(scope)){scopeIds.set(scope,scopeNames.length);scopeNames.push(scope);}return scopeIds.get(scope);});
  const history=[0,0,0];
  for(const next of [...tokens,1]){
   for(const scope of scopes)for(let n=0;n<4;n++){
    const key=scope+'|'+(n?history.slice(-n).join(','):''),entry=counts[key]||(counts[key]={});entry[next]=(entry[next]||0)+row.weight;
   }
   history.push(next);
  }
 }
 const preferences=JSON.parse(fs.readFileSync(new URL('preference-pairs.json',import.meta.url))),preference=trainPreference(preferences.pairs);
 const digest=crypto.createHash('sha256').update(JSON.stringify({rows,preferences})).digest('hex');
 return {schemaVersion:1,version:'2026-10-04.prediction-1',order:4,vocabulary,scopes:scopeNames,counts,paths:compiled,featureNames,preferenceWeights:preference.weights,training:{sourceSha256:digest,paths:compiled.length,uniquePaths:new Set(compiled.map(r=>r.language+':'+r.kind+':'+r.tokens.join(','))).size,tokens:compiled.reduce((n,r)=>n+r.tokens.length+1,0),vocabulary:vocabulary.length,contexts:Object.keys(counts).length,pairs:preferences.pairs.length,epochs:preference.epochs,initialPreferenceLoss:Number(preference.initialLoss.toFixed(6)),finalPreferenceLoss:Number(preference.finalLoss.toFixed(6)),corpusNote:preferences.description}};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const started=performance.now(),model=trainGeneration(),out=new URL('../docs/generation-model.js',import.meta.url);
 const source='// Generated by node training/train-generation.mjs. Do not edit weights by hand.\nexport const generationModel='+JSON.stringify(model)+';\n';
 if(process.argv.includes('--check')){
  if(fs.readFileSync(out,'utf8')!==source)throw Error('Generation model is stale; retrain it.');
 }else fs.writeFileSync(out,source);
 console.log(JSON.stringify({...model.training,bytes:Buffer.byteLength(source),elapsedMs:Math.round(performance.now()-started)},null,2));
}
