"""Bind actual full-output reviews; explore tokenization aliases without inference."""
import hashlib
import json
import pathlib

R = pathlib.Path(__file__).resolve().parent
REPO = R.parents[3]
read = lambda p: json.loads(p.read_text())
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
raw_path = R / 'results/raw-generations.json'
raw = read(raw_path)['rows']
tf = read(R / 'results/tf-results.json')['rows']
panel = read(R / 'panel.json')
pieces = [bytes.fromhex(s) for s in read(REPO / panel['tokenizerPath'])['bytes']]
notes = [read(R / 'results' / name) for name in
         ['train-independent-reading.json', 'dev-independent-reading.json']]
grades = {(x['id'], x['condition']): x for note in notes for x in note['rows']}
assert len(raw) == len(grades) == 75
assert set(grades) == {(x['id'], x['condition']) for x in raw}
assert all(note.get('rawFileSha256') == sha(raw_path) for note in notes)


def token_at_character(row, character):
    text = row['text']
    assert text is not None and 0 <= character < len(text)
    offset = len(text[:character].encode('utf8'))
    cursor = 0
    for j, token in enumerate(row['nonEosTokens']):
        end = cursor + len(pieces[token])
        if cursor <= offset < end:
            return dict(characterIndex=character, utf8ByteOffset=offset,
                        generatedTokenIndex=j, tokenId=token)
        cursor = end
    raise AssertionError('Character does not map to generated bytes')


mapped = []
seen = {}
for row in raw:
    grade = grades[row['id'], row['condition']]
    key = row['prefixText'], row['text']
    judgment = tuple(grade[k] for k in ['naturalWhole', 'genericOnly', 'longLoop'])
    if key in seen:
        assert seen[key] == judgment, 'Identical full output received inconsistent core judgment'
    seen[key] = judgment
    for name in ['firstGrammarBreakCharacter', 'firstTopicBreakCharacter', 'firstHarmfulRepetitionCharacter']:
        at = grade.get(name)
        if at is not None:
            mapped.append(dict(id=row['id'], condition=row['condition'], kind=name,
                               **token_at_character(row, at), reason=grade['reason']))

# Explicit illustrative root readings, additional to independently recorded
# onsets. Conservative repeated-run markers are not a new language gate.
illustrations = []
spec = [
    ('train-jmrd-03', 'correct', 'お願いします。\n', 3),
    ('content-native-05', 'mismatched', '書', 3),
    ('content-native-04', 'correct', '暑いので暑いので暑いので', 1),
    ('fresh-mrmp-03', 'mismatched', '食べたいですね。', 3),
]
for case_id, condition, phrase, occurrence in spec:
    row = next(x for x in raw if x['id'] == case_id and x['condition'] == condition)
    text = row['text']; start = -1
    for _ in range(occurrence):
        start = text.find(phrase, start + 1)
        assert start >= 0
    if case_id == 'content-native-05':
        # Find the first run of three identical characters rather than counting
        # the separate 書 characters in 読書館/読書 before the run.
        start = text.index('書書書') + 2
    if case_id == 'content-native-04':
        start += 2 * len('暑いので')
    illustrations.append(dict(id=case_id, condition=condition, quote=text[start:start+25],
        **token_at_character(row, start),
        interpretation='Root actual reading: conservative point in a clearly harmful repetitive run; not a universally earliest onset or mechanical-4gram quality rule'))

alias_counts = dict(tokens=0, exactCanonicalId=0, bytePrefixCompatible=0,
                    nonExactButBytePrefixCompatible=0)
for row in tf:
    if row['caseGroup'] != 'primary' or row['condition'] != 'correct':
        continue
    target = row['targetText'].encode('utf8'); cursor = 0
    for score in row['tokens']:
        predicted = pieces[score['top1Token']]
        compatible = score['top1Token'] >= 6 and bool(predicted) and target[cursor:].startswith(predicted)
        alias_counts['tokens'] += 1
        alias_counts['exactCanonicalId'] += score['goldIsTop1']
        alias_counts['bytePrefixCompatible'] += compatible
        alias_counts['nonExactButBytePrefixCompatible'] += compatible and not score['goldIsTop1']
        cursor += len(pieces[score['goldToken']])
    assert cursor == len(target)

groups = []
for split in ['TRAIN', 'exposed-DEV']:
    for condition in ['correct', 'mismatched', 'none']:
        selected = [x for x in raw if x['split'] == split and x['condition'] == condition]
        selected_grades = [grades[x['id'], condition] for x in selected]
        def appropriate(g):
            if condition == 'none': return None
            if split == 'TRAIN': return g['appropriateResponse']
            return g['naturalWhole'] and g['contextRelevant'] is True and not g['longLoop']
        groups.append(dict(split=split, condition=condition, outputs=len(selected),
            naturalWhole=sum(g['naturalWhole'] for g in selected_grades),
            genericOnly=sum(g['genericOnly'] for g in selected_grades),
            longLoop=sum(g['longLoop'] for g in selected_grades),
            appropriateWholeResponses=None if condition == 'none' else sum(appropriate(g) for g in selected_grades),
            independenceCaution='TRAIN original contextRelevant denotes broad topic linkage; appropriateResponse is the separate strict conversational-act dimension'))

output = dict(rawFileSha256=sha(raw_path), panelSha256=sha(R / 'panel.json'),
    sourceCodeSha256=sha(pathlib.Path(__file__)),
    reviewFileSha256={name: sha(R / 'results' / name) for name in
        ['train-independent-reading.json', 'dev-independent-reading.json']},
    all75CompletePrefixesAndContinuationsActuallyReadByRoot=True,
    independentAssistantTrainOutputs=36, independentAssistantDevOutputs=39,
    independentBlindHumanEvaluation=False, uniquePrefixFullTextPairs=len(seen),
    identicalCoreJudgmentsConsistent=True, historicalGradesOverwritten=False,
    noAutomaticSemanticGrader=True, groups=groups, independentlyAnnotatedOnsets=mapped,
    rootIllustrativeRepetitionMarkers=illustrations,
    exploratoryTokenizationAliasCheck=dict(**alias_counts,
        plannedPrimaryMetricsUnchanged=True, status='Post-output read-only control, not a replacement accuracy metric',
        interpretation='A nonmatching BPE ID can still begin the same gold byte suffix. This local compatibility does not certify a complete word, semantics or unique gold correctness.'),
    actualOptimizerObjectsConstructed=0, actualOptimizerUpdates=0)
path = R / 'results/reading-complete.json'
assert not path.exists(), 'Preserve an existing review result'
path.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n')
print(json.dumps(dict(outputs=75, uniquePrefixFullTextPairs=len(seen), groups=groups,
                     exploratoryTokenizationAliasCheck=alias_counts), ensure_ascii=False))
