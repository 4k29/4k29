"""Validate the frozen comparison, held-out separation, outputs and Git archives."""
import gzip
import hashlib
import io
import json
from collections import Counter
from prepare import ROOT,BASE,FAMILY,REPO,read,sha,blob

def validate():
    plan=read(ROOT/'PLAN.json')
    assert sha((ROOT/'PLAN.json').read_bytes())==(ROOT/'PLAN.sha256').read_text().strip()
    for file,value in plan['frozen'].items():
        assert sha((ROOT/file).read_bytes())==value
    schedule=read(ROOT/'SCHEDULE.json')
    replay=read(ROOT/'REPLAY.json')
    monitor=read(ROOT/'MONITOR.json')
    train=read(FAMILY/'TRAIN.json')
    pieces=[bytes.fromhex(t) for t in read(BASE/'data/tokenizer.json')['bytes']]
    held=set(read(ROOT/'PROVENANCE.json')['held_dev_ids'])
    assert len({r['family'] for r in replay+monitor})==len(replay+monitor)
    for r in replay+monitor:
        assert r['id'] not in held and r['prefix']==[1] and r['gold'][-1]==2
        assert sha(b''.join(pieces[t] for t in r['gold'][:-1]))==r['source_text_sha256']
    assert len(schedule['C'])==len(schedule['D'])==300
    for c,d in zip(schedule['C'],schedule['D'],strict=True):
        assert c['prose']==d['prose'] and c['denominator']==d['denominator'] and not d['replay']
    initial=set()
    for arm,target in [('B',(69019,23006)),('C',(46013,46012)),('D',(46013,0))]:
        ledger=read(ROOT/f'{arm}-ledger.json')
        receipt=read(ROOT/f'{arm}-receipt.json')
        assert receipt['retained']==300 and receipt['optimizer_calls']==301
        initial.add(receipt['initial_sha'])
        assert read(ROOT/f'{arm}-resume.json')['row']==ledger[100]
        assert tuple(sum(row[k] for row in ledger) for k in ('prose','replay'))==target
        unique=set()
        for i,(s,row) in enumerate(zip(schedule[arm],ledger,strict=True),1):
            assert row['step']==i
            assert row['denominator']==s['denominator']==(307 if i<=225 else 306)
            for kind,records in [('prose',train),('replay',replay)]:
                assert row[kind]==sum(n for _,_,n in s[kind])
                for index,start,count in s[kind]:
                    assert 0<=start<start+count<=len(records[index]['gold'])
                    if kind=='replay':
                        for j in range(start,start+count):
                            assert (index,j) not in unique
                            unique.add((index,j))
        for i in plan['steps'][1:]:
            rows=json.load(gzip.open(ROOT/f'{arm}-{i}.json.gz'))['cases']
            assert Counter(r['panel'] for r in rows)=={'prose':18,'caption':32,'train':14}
            for r in rows:
                assert [s['top5'][0][0] for s in r['steps']]==r['generated']
                assert len(r['generated'])<=r['budget'] and not r['forced']
                assert b''.join(pieces[t] for t in r['generated']).hex()==r['raw_hex']
        for i in (100,300):
            import torch
            folder=ROOT/'artifacts'/f'{arm}-{i}'
            manifest=read(folder/'checkpoint.json')
            raw=io.BytesIO()
            digest=hashlib.sha256()
            for part in manifest['chunks']:
                content=blob(folder/part['path'])
                assert sha(content)==part['sha256']
                raw.write(content)
                digest.update(content)
            assert digest.hexdigest()==manifest['sha256']
            raw.seek(0)
            state=torch.load(raw,map_location='cpu',weights_only=False)['trajectory']
            assert state['uniqueUpdates']==i and state['history']==ledger[:i]
            assert {int(v['step']) for v in state['optimizer']['state'].values()}=={i}
    assert len(initial)==1
    print('PASS matched masks, replay provenance, generated bytes, six Git-only complete states')

if __name__=='__main__':
    validate()
